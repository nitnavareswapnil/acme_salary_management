CREATE TABLE employee (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)   NOT NULL,
    email       VARCHAR(255)   NOT NULL,
    department  VARCHAR(100)   NOT NULL,
    job_title   VARCHAR(100)   NOT NULL,
    country     VARCHAR(20)    NOT NULL,
    base_salary DECIMAL(15, 2) NOT NULL
);

CREATE UNIQUE INDEX uk_employee_email ON employee (email);
-- Support the insight GROUP BY queries and the directory filters.
CREATE INDEX idx_employee_country ON employee (country);
CREATE INDEX idx_employee_job_title ON employee (job_title);
CREATE INDEX idx_employee_department ON employee (department);
